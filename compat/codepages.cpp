// ===========================================================================
// Single characters
// ===========================================================================

bool M2W_CodePageKnown(int iCodePage)
{
    return TableFor(iCodePage) != nullptr;
}

char32_t M2W_ByteToChar(int iCodePage, unsigned char uByte)
{
    const char32_t* c_pkTable = TableFor(iCodePage);
    if (!c_pkTable)
        return UNASSIGNED;
    return c_pkTable[uByte];
}

bool M2W_CharToByte(int iCodePage, char32_t cChar, unsigned char* puByte)
{
    const char32_t* c_pkTable = TableFor(iCodePage);
    if (!c_pkTable || !puByte)
        return false;

    // The sentinel is not a character. Earlier the search below
    // found it like a real assignment: asking for U+FFFD returned `true`
    // and the first UNASSIGNED byte (0x81 in all three pages), so
    // `WideCharToMultiByte` in platform_codec.cpp wrote 0x81 without setting
    // `lpUsedDefaultChar`, and an unassigned byte going decode-encode
    // silently became 0x81.
    if (cChar == UNASSIGNED)
        return false;

    // Linear search, first (lowest) byte wins. No page has two bytes for one
    // character (audit), so "first" never has to choose.
    for (int i = 0; i < 256; ++i)
    {
        if (c_pkTable[i] == cChar)
        {
            *puByte = static_cast<unsigned char>(i);
            return true;
        }
    }
    return false;
}

// ===========================================================================
// Whole strings
// ===========================================================================

int M2W_ToUtf16(int iCodePage, const char* c_szInput, int iBytes,
                char16_t* pOutput, int iCapacity)
{
    if (!M2W_CodePageKnown(iCodePage) || !c_szInput)
        return 0;

    // Negative length: zero-terminated, and the zero belongs to the string.
    int iCount = iBytes;
    if (iBytes < 0)
    {
        iCount = 0;
        while (c_szInput[iCount] != '\0')
            ++iCount;
        ++iCount;
    }

    // Every byte becomes 1 or 2 units; UNASSIGNED is in the BMP, so 1.
    int iNeeded = 0;
    for (int i = 0; i < iCount; ++i)
        iNeeded += Utf16Units(M2W_ByteToChar(iCodePage, static_cast<unsigned char>(c_szInput[i])));

    if (iCapacity == 0)
        return iNeeded;
    if (iNeeded > iCapacity)
        return 0;

    int iPos = 0;
    for (int i = 0; i < iCount; ++i)
    {
        const char32_t c = M2W_ByteToChar(iCodePage, static_cast<unsigned char>(c_szInput[i]));
        if (c < 0x10000u)
        {
            pOutput[iPos++] = static_cast<char16_t>(c);
        }
        else
        {
            // Surrogate pair for characters outside the BMP. No table entry
            // is that high today; kept so the contract holds if one is added.
            const char32_t cu = c - 0x10000u;
            pOutput[iPos++] = static_cast<char16_t>(0xD800u | (cu >> 10));
            pOutput[iPos++] = static_cast<char16_t>(0xDC00u | (cu & 0x3FFu));
        }
    }
    return iNeeded;
}

int M2W_FromUtf16(int iCodePage, const char16_t* c_pInput, int iUnits,
                  char* pOutput, int iCapacity)
{
    if (!M2W_CodePageKnown(iCodePage) || !c_pInput)
        return 0;

    const int iCount = (iUnits < 0) ? UnitsWithTerminator(c_pInput) : iUnits;

    // A complete surrogate pair (2 units) -> 1 byte; a lone surrogate -> 1
    // byte ('?'); a BMP character -> 1 byte. So: one byte per character.
    int iNeeded = 0;
    for (int i = 0; i < iCount; ++i)
    {
        const char16_t u = c_pInput[i];
        if (u >= 0xD800u && u <= 0xDBFFu &&
            i + 1 < iCount && c_pInput[i + 1] >= 0xDC00u && c_pInput[i + 1] <= 0xDFFFu)
            ++i;    // the low half of the pair is consumed too
        ++iNeeded;
    }

    if (iCapacity == 0)
        return iNeeded;
    if (iNeeded > iCapacity)
        return 0;

    int iPos = 0;
    for (int i = 0; i < iCount; ++i)
    {
        const char16_t u = c_pInput[i];
        char32_t cChar;
        if (u >= 0xD800u && u <= 0xDBFFu)
        {
            if (i + 1 < iCount && c_pInput[i + 1] >= 0xDC00u && c_pInput[i + 1] <= 0xDFFFu)
            {
                // Complete pair -> the full code point (which no page has, so
                // it ends up as '?' below - ONE for the pair).
                const char32_t hi = u - 0xD800u;
                const char32_t lo = c_pInput[i + 1] - 0xDC00u;
                cChar = 0x10000u + (hi << 10) + lo;
                ++i;
            }
            else
            {
                cChar = static_cast<char32_t>('?');    // lone high surrogate
            }
        }
        else if (u >= 0xDC00u && u <= 0xDFFFu)
        {
            cChar = static_cast<char32_t>('?');        // lone low surrogate
        }
        else
        {
            cChar = static_cast<char32_t>(u);
        }

        unsigned char uByte;
        pOutput[iPos++] = M2W_CharToByte(iCodePage, cChar, &uByte) ? static_cast<char>(uByte) : '?';
    }
    return iNeeded;
}
