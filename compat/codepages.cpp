/// The table for a code page, or null when unknown.
const char32_t* TableFor(int iCodePage)
{
    switch (iCodePage)
    {
        case M2W_CP_1252: return kCP1252;
        case M2W_CP_1250: return kCP1250;
        case M2W_CP_874:  return kCP874;
        default:          return nullptr;
    }
}

/// UTF-16 units needed for one character: 2 for a surrogate pair.
int Utf16Units(char32_t c)
{
    return (c < 0x10000u) ? 1 : 2;
}

/// Length of a UTF-16 string INCLUDING the terminating zero.
int UnitsWithTerminator(const char16_t* c_pInput)
{
    int iUnits = 0;
    while (c_pInput[iUnits] != 0)
        ++iUnits;
    return iUnits + 1;
}

